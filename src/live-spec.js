// generator all read the same thing. Recorded from the live app's menu tree and screenshots, and from the widget
// code, on 2026-11-11.
//
// Three levels, as in Creator:  section (the dropdown)  →  page (the tab row)  →  inner tabs, stat cards and buttons.
//
// status:  built        the page matches the live one
//          partial      the page exists but is not yet at parity (the parity baseline lists what is missing)
//          placeholder  the page does not exist yet; the menu shows a clearly labelled "Not built yet" page
// component: the name of the React component (resolved in nav.js)
// tabs / stats / buttons: the labels the live page shows. The parity test checks each one is on our page.

const page = (path, label, component, status, blurb, tabs = [], stats = [], buttons = [], extra = {}) => ({
  path, label, component, status, blurb, tabs, stats, buttons, ...extra,
});

